"""Build the web app into a folder: the UI of the desktop app + the JavaScript port of the logic (web/) + the draws
file + PWA files (manifest, service worker, icons).  The same folder is
  - published on GitHub Pages (iPhone / any browser: "Add to Home Screen"),
  - wrapped into the Android app (Capacitor).

Usage:  python -m tools.build_site [--out site] [--data app/seed/draws.json] [--version 1.4.0]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UI = ROOT / "app" / "ui"
LOCALES = ROOT / "app" / "locales"
WEB = ROOT / "web"
SKIP_UI = {"icon.ico"}

MANIFEST = {
    "name": "EuroJackpot Analyzer", "short_name": "EuroJackpot", "start_url": "./", "scope": "./", "display": "standalone",
    "orientation": "portrait", "background_color": "#0b1020", "theme_color": "#0b1020", "lang": "el",
    "description": "EuroJackpot statistics, ticket generator and prize check",
    "icons": [
        {"src": "icons/icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any"},
        {"src": "icons/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any"},
        {"src": "icons/icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
    ],
}

HEAD_EXTRA = """<link rel="manifest" href="manifest.webmanifest">
<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
<link rel="icon" type="image/png" sizes="32x32" href="icons/favicon-32.png">
<meta name="theme-color" content="#0b1020">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="EuroJackpot">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
"""

SW = """/* Generated by tools/build_site.py - offline use and automatic updates of the web app. */
const CACHE = "ejp-%(hash)s";
const PRECACHE = %(files)s;
const NETWORK_FIRST = ["/data/draws.json", "/version.json"];

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith("ejp-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  const req = e.request, url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== location.origin) return;
  if (NETWORK_FIRST.some((p) => url.pathname.endsWith(p))) {          // data: always try the network first, fall back to the stored copy
    e.respondWith(fetch(req).then((r) => { const copy = r.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); return r; })
      .catch(() => caches.match(req, { ignoreSearch: true })));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).catch(() => (req.mode === "navigate" ? caches.match("index.html") : Response.error()))));
});
"""


def read_version() -> str:
    m = re.search(r'or "([\d.]+)"', (ROOT / "app" / "version.py").read_text(encoding="utf-8"))
    return m.group(1) if m else "0.0.0"


def build(out: Path, data: Path, version: str) -> Path:
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    # the UI of the desktop app
    for p in UI.rglob("*"):
        if p.is_file() and p.name not in SKIP_UI:
            dest = out / p.relative_to(UI)
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(p, dest)
    shutil.copytree(LOCALES, out / "locales")
    # the JavaScript logic
    (out / "web").mkdir()
    for p in WEB.glob("*.js"):
        shutil.copy2(p, out / "web" / p.name)
    (out / "web" / "version.js").write_text(
        f'export const VERSION = "{version}";\nexport const REPO = "VeZReVouLiS/EuroJackpot-Analyzer";\n'
        'export const PAGES = "https://vezrevoulis.github.io/EuroJackpot-Analyzer/";\n', encoding="utf-8")
    shutil.copytree(WEB / "icons", out / "icons")
    # data
    (out / "data").mkdir()
    shutil.copy2(data, out / "data" / "draws.json")
    # index.html: PWA tags, safe-area viewport, and the in-browser API
    html = (UI / "index.html").read_text(encoding="utf-8")
    html = html.replace('<meta name="viewport" content="width=device-width, initial-scale=1">',
                        '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">')
    html = html.replace("</head>", HEAD_EXTRA + "</head>", 1)
    html = html.replace('<script src="vendor/chart.umd.min.js"></script>',
                        '<script>window.EJ_WEB = true;</script>\n<script type="module" src="web/boot.js"></script>\n<script src="vendor/chart.umd.min.js"></script>', 1)
    assert "web/boot.js" in html and "viewport-fit=cover" in html
    (out / "index.html").write_text(html, encoding="utf-8")
    (out / "manifest.webmanifest").write_text(json.dumps(MANIFEST, indent=1), encoding="utf-8")
    (out / "version.json").write_text(json.dumps({"version": version, "built": datetime.now(timezone.utc).isoformat(timespec="seconds")}), encoding="utf-8")
    (out / ".nojekyll").write_text("", encoding="utf-8")
    # service worker: cache name = hash of everything that is cached (data and version.json change independently)
    files = sorted(p.relative_to(out).as_posix() for p in out.rglob("*") if p.is_file() and p.name not in ("sw.js", ".nojekyll"))
    h = hashlib.sha1()
    for f in files:
        if f not in ("data/draws.json", "version.json"):
            h.update(f.encode()); h.update((out / f).read_bytes())
    precache = ["./"] + files
    (out / "sw.js").write_text(SW % {"hash": h.hexdigest()[:12], "files": json.dumps(precache)}, encoding="utf-8")
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "site"))
    ap.add_argument("--data", default=str(ROOT / "app" / "seed" / "draws.json"))
    ap.add_argument("--version", default=None)
    a = ap.parse_args()
    out = build(Path(a.out), Path(a.data), a.version or read_version())
    size = sum(p.stat().st_size for p in out.rglob("*") if p.is_file())
    print(f"built {out} ({size // 1024} KB)")


if __name__ == "__main__":
    main()
